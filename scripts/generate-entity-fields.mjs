#!/usr/bin/env node
// HEDGE-168 — produce `generated/entities/<entity>/index.ts` for a @freighttech
// package, the per-entity field lists the host app's entity-fields registry is
// assembled from.
//
// WHY THIS SCRIPT EXISTS AT ALL. `mercato generate` writes these files for a
// package only when it thinks it is running inside the framework's own
// monorepo, and it decides that by asking whether `node_modules/@open-mercato/core`
// is a SYMLINK (`@open-mercato/cli`, `resolver.ts`). We install the platform
// from Verdaccio, so it is a real directory, the CLI runs STANDALONE, and
// `generateEntityIds()` skips every group that is not `@app`:
//
//     for (const g of groups) {
//       if (!resolver.isMonorepo() && g !== '@app') continue
//       ...
//       writePerEntityFieldFiles(fieldsRoot, combined)
//     }
//
// In the same mode `loadStandaloneGeneratedPackageEntities()` READS those files
// back out of the package to build `entityFieldMap`. So the one code path that
// consumes them is live here while the one that produces them is not, and every
// @freighttech entity contributed zero fields — 114 of 179 entities in `E` had
// no fields at all on 2026-08-26, and `entity-fields-registry.ts` held 65
// entities, all of them from `@open-mercato/core`.
//
// The parsing below is a deliberate BUG-FOR-BUG copy of the CLI's
// `parseExportedClassNamesFromFile` + `parseEntityFieldsFromFile` + `toSnake` /
// `toVar`. It has to predict what the CLI would have written, not what a
// reasonable person would write, or the two halves of the pipeline disagree.
//
// Consumed by `scripts/build-package.mjs`, so it runs on every package `build`
// AND on `prepack` — the latter is what gets the files into the Verdaccio
// tarball that Tier-3 apps install.
//
// Usage:
//   node scripts/generate-entity-fields.mjs                 # package in cwd
//   node scripts/generate-entity-fields.mjs --all           # every packages/*
//   node scripts/generate-entity-fields.mjs --check --all   # report drift, write nothing
//   node scripts/generate-entity-fields.mjs <pkgRoot> ...

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const HEADER = [
  '// AUTO-GENERATED by scripts/generate-entity-fields.mjs (HEDGE-168). Do not edit.',
  '//',
  "// One file per entity, named `toSnake(ClassName)` — NOT the table name. Each",
  '// export is a database column name, mirroring what `mercato generate` writes',
  '// for `@open-mercato/*` packages. `loadStandaloneGeneratedPackageEntities()`',
  '// reads these back to build the host app\'s `entity-fields-registry.ts`, which',
  '// is what the Encryption and Translation managers list fields from.',
  '//',
  '// Regenerate with `node scripts/generate-entity-fields.mjs --all`; the package',
  '// build does it for you. Guarded by',
  '// `apps/web/src/__tests__/entity-fields-registry-contract.test.ts`.',
  '',
].join('\n')

const MODULE_CODE_EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx']
/** `bases` × `candidates` in the order `generateEntityIds()` tries them. */
const ENTITY_FILE_BASES = ['data', 'db']
const ENTITY_FILE_CANDIDATES = ['entities.override', 'entities', 'schema']

/** `toSnake` from `@open-mercato/cli/src/lib/utils.ts`. No pluralisation. */
function toSnake(s) {
  return s
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/\W+/g, '_')
    .replace(/_{2,}/g, '_')
    .replace(/(?:^_+|_+$)/g, '')
    .toLowerCase()
}

/** `toVar` from the same file. */
function toVar(s) {
  return s.replace(/[^a-zA-Z0-9_]/g, '_')
}

// `export const default = "default"` is a syntax error, and a column may well be
// called `default`, `class` or `new`. The CLI would emit it verbatim and break
// the build; we keep the VALUE (which is all the reader uses — it collects
// string-literal initializers, not identifier names) and make the binding legal.
const RESERVED = new Set([
  'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default',
  'delete', 'do', 'else', 'enum', 'export', 'extends', 'false', 'finally',
  'for', 'function', 'if', 'import', 'in', 'instanceof', 'new', 'null',
  'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof',
  'var', 'void', 'while', 'with', 'let', 'static', 'yield', 'await',
  'implements', 'interface', 'package', 'private', 'protected', 'public',
])

function toBinding(field) {
  let name = toVar(field)
  if (!name || /^[0-9]/.test(name)) name = `_${name}`
  if (RESERVED.has(name)) name = `${name}_`
  return name
}

function createSourceFile(filePath) {
  return ts.createSourceFile(
    filePath,
    readFileSync(filePath, 'utf8'),
    ts.ScriptTarget.ES2020,
    true,
    ts.ScriptKind.TS,
  )
}

/** `parseExportedClassNamesFromFile` — TOP-LEVEL classes with an `export` modifier. */
function exportedClassNames(sf) {
  const names = []
  sf.forEachChild((node) => {
    if (!ts.isClassDeclaration(node) || !node.name) return
    if (!node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) return
    names.push(node.name.text)
  })
  return names
}

/** The `{ name: '...' }` of a decorator call's first argument, if it has one. */
function decoratorNameLiteral(dec) {
  const expr = dec.expression
  if (!ts.isCallExpression(expr) || !expr.arguments.length) return undefined
  const first = expr.arguments[0]
  if (!ts.isObjectLiteralExpression(first)) return undefined
  for (const prop of first.properties) {
    if (!ts.isPropertyAssignment(prop)) continue
    if (!ts.isIdentifier(prop.name) || prop.name.text !== 'name') continue
    if (ts.isStringLiteral(prop.initializer)) return prop.initializer.text
  }
  return undefined
}

/**
 * `parseEntityFieldsFromFile`. Copied faithfully, including the part a reviewer
 * would call a bug: the CLI breaks out of the decorator loop on the FIRST
 * decorator, so `@Index() @Property({ name: 'x' })` yields `toSnake(prop)` and
 * not `x`. Diverging here would make the files we write differ from the ones
 * `mercato generate` writes for `@open-mercato/*`, which is the whole point.
 */
function entityFields(sf, exportedNames) {
  const exported = new Set(exportedNames)
  const result = {}
  sf.forEachChild((node) => {
    if (!ts.isClassDeclaration(node) || !node.name) return
    if (!exported.has(node.name.text)) return
    const fields = []
    for (const member of node.members) {
      if (!ts.isPropertyDeclaration(member) || !member.name) continue
      const name = ts.isIdentifier(member.name)
        ? member.name.text
        : ts.isStringLiteral(member.name)
          ? member.name.text
          : undefined
      if (!name) continue
      if (member.modifiers?.some((m) => m.kind === ts.SyntaxKind.StaticKeyword)) continue
      const decorators = ts.canHaveDecorators(member) ? (ts.getDecorators(member) ?? []) : []
      let dbName
      for (const d of decorators) {
        dbName = decoratorNameLiteral(d) || toSnake(name)
        if (dbName) break
      }
      if (!dbName) dbName = toSnake(name)
      fields.push(dbName)
    }
    result[toSnake(node.name.text)] = Array.from(new Set(fields))
  })
  return result
}

function resolveEntitiesFile(moduleDir) {
  for (const base of ENTITY_FILE_BASES) {
    for (const candidate of ENTITY_FILE_CANDIDATES) {
      for (const ext of MODULE_CODE_EXTENSIONS) {
        const p = join(moduleDir, base, `${candidate}${ext}`)
        if (existsSync(p)) return p
      }
    }
  }
  return null
}

/** Every entity of every module in the package, merged — `combined` in the CLI. */
export function collectPackageEntityFields(pkgRoot) {
  const modulesRoot = join(pkgRoot, 'src', 'modules')
  if (!existsSync(modulesRoot)) return {}
  const combined = {}
  for (const entry of readdirSync(modulesRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const entitiesFile = resolveEntitiesFile(join(modulesRoot, entry.name))
    if (!entitiesFile) continue
    const sf = createSourceFile(entitiesFile)
    const map = entityFields(sf, exportedClassNames(sf))
    for (const [entity, fields] of Object.entries(map)) {
      combined[entity] = Array.from(new Set([...(combined[entity] ?? []), ...fields]))
    }
  }
  return combined
}

export function renderEntityFieldsFile(fields) {
  const lines = fields.map((field) => `export const ${toBinding(field)} = ${JSON.stringify(field)};`)
  return `${HEADER}${lines.join('\n')}\n`
}

/**
 * @returns {{ written: string[], removed: string[], unchanged: string[] }}
 */
export function writePackageEntityFields(pkgRoot, { check = false } = {}) {
  const combined = collectPackageEntityFields(pkgRoot)
  const outRoot = join(pkgRoot, 'generated', 'entities')
  const written = []
  const unchanged = []
  const removed = []

  const entities = Object.keys(combined).sort()
  for (const entity of entities) {
    const outFile = join(outRoot, entity, 'index.ts')
    const next = renderEntityFieldsFile(combined[entity])
    const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null
    if (current === next) {
      unchanged.push(outFile)
      continue
    }
    written.push(outFile)
    if (check) continue
    mkdirSync(dirname(outFile), { recursive: true })
    writeFileSync(outFile, next)
  }

  if (existsSync(outRoot)) {
    const desired = new Set(entities)
    for (const entry of readdirSync(outRoot, { withFileTypes: true })) {
      if (!entry.isDirectory() || desired.has(entry.name)) continue
      removed.push(join(outRoot, entry.name))
      if (!check) rmSync(join(outRoot, entry.name), { recursive: true, force: true })
    }
  }

  return { written, removed, unchanged }
}

function packageRoots(args) {
  if (args.includes('--all')) {
    const packagesDir = join(REPO_ROOT, 'packages')
    return readdirSync(packagesDir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && existsSync(join(packagesDir, e.name, 'package.json')))
      .map((e) => join(packagesDir, e.name))
      .sort()
  }
  const explicit = args.filter((a) => !a.startsWith('--'))
  return explicit.length ? explicit.map((p) => resolve(p)) : [process.cwd()]
}

function main() {
  const args = process.argv.slice(2)
  const check = args.includes('--check')
  const quiet = args.includes('--quiet')
  let drift = 0
  let entityCount = 0

  for (const pkgRoot of packageRoots(args)) {
    const { written, removed, unchanged } = writePackageEntityFields(pkgRoot, { check })
    entityCount += written.length + unchanged.length
    drift += written.length + removed.length
    if (quiet || (!written.length && !removed.length)) continue
    const label = relative(REPO_ROOT, pkgRoot) || pkgRoot
    const verb = check ? 'stale' : 'wrote'
    console.log(
      `[entity-fields] ${label}: ${verb} ${written.length}, removed ${removed.length}, unchanged ${unchanged.length}`,
    )
    for (const file of [...written, ...removed]) {
      console.log(`[entity-fields]   ${relative(REPO_ROOT, file)}`)
    }
  }

  if (check && drift > 0) {
    console.error(
      `[entity-fields] ${drift} file(s) out of date. Run \`node scripts/generate-entity-fields.mjs --all\` and commit the result.`,
    )
    process.exit(1)
  }
  if (!quiet && check) console.log(`[entity-fields] ${entityCount} entity field file(s) up to date`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main()
}
